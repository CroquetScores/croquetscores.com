-- Everything the database holds, made at once.
--
-- The site has no real data yet, so the schema is kept as one file, written as
-- it now stands, rather than as the migrations that grew it. A database made
-- by an earlier shape of this file is made again, with npm run db:down and
-- db:up in development. Once a site holds real data this file is never
-- rewritten, and what changes the schema from then on is a file of its own,
-- since a database that has applied one is told it has by its name.

-- Every event ever recorded, in the stream of the thing it happened to, in the
-- order it happened. Rows are only ever added.
--
-- An event is kept as the registry wrote it down: the name its kind goes by, and
-- everything it said as JSON. Its moment is in there as text, in UTC, as the
-- event wrote it, rather than lifted into a timestamp column, so that the
-- database's own time zone has no say in when anything happened.
--
-- The key is what makes two commands appending to one stream at once safe.
-- Both may find the stream at the same version and try to add the next; the
-- second has to wait for the first to finish, and then finds the version taken.
--
-- `id` is a number the database gives each event as it is kept, which only
-- goes up. A stream and its version say which event it is; this says where,
-- among every event there is, it was kept, so that somebody who has read as
-- far as a number can ask for what came after it without comparing every
-- stream. Given by default and not always, so that a copy of the events kept
-- somewhere else can keep the number it was given here (backupCli.feature).
create table events (
    id        bigint  generated by default as identity,
    stream_id text    not null,
    version   integer not null,
    name      text    not null,
    data      jsonb   not null,
    constraint one_event_per_version primary key (stream_id, version)
);

create unique index events_by_id on events (id);

-- Each account's own key, encrypted with the site's key, and a mark of which
-- site's key that was: a keyed hash of a fixed text, made with it, which says
-- nothing of the key and lets a store opened with another be refused as that
-- rather than finding every key tampered with. Deleting a row forgets its
-- account: what is kept of its name and email address can never be read again.
--
-- An account is forgotten by rewriting what is personal in its events, and its
-- key is kept, so a key can no longer be told forgotten by being missing.
-- `forgotten` says so.
create table account_keys (
    account_id    text    primary key,
    key           bytea   not null,
    site_key_mark text    not null,
    forgotten     boolean not null default false
);

-- Accounts by a keyed hash of their email address, never the address itself.
-- A forgotten account keeps its row, marked, and is never found by it again;
-- no row is ever deleted. An address has one account at a time among those not
-- forgotten, which is what stops two registrations of one address, sent at
-- once, both making an account.
--
-- Whether each account is confirmed is kept for whatever gives an account
-- something by its address to ask in one query rather than by loading the
-- account. An account is confirmed when its address is, or when it came over
-- from the old site, and is never unconfirmed afterwards.
create table accounts_by_email_address (
    account_id         text    primary key,
    email_address_hash text    not null,
    forgotten          boolean not null default false,
    confirmed          boolean not null default false
);

create unique index one_account_per_email_address
    on accounts_by_email_address (email_address_hash)
    where not forgotten;

-- Emails to be sent, each queued in the transaction of the command it is about,
-- so that it is queued if and only if what it is about is kept. It holds no
-- words: its kind and its language say what the email writer is to write when
-- it is sent. Where it goes and whatever fills it in are sealed, with its
-- account's key when it is about an account, and with the site's key when it
-- is not, so that no address is kept as it was given. Moments are timestamps
-- in UTC.
--
-- `queued` is the order emails were queued in, for those due at the same
-- moment. Two emails queued by one request are due at the same moment, and so
-- can be two queued by two requests in the same instant; nothing else says
-- which came first. The id cannot, being random, and the order rows happen to
-- be kept in changes whenever one is updated.
create table email_queue (
    id                text        primary key,
    account_id        text,
    kind              text        not null,
    language          text        not null,
    sealed            text        not null,
    link_works_until  timestamptz,
    due_at            timestamptz not null,
    tries             integer     not null default 0,
    last_tried_at     timestamptz,
    given_up_at       timestamptz,
    queued            bigint      generated always as identity
);

-- What sending looks for, in the order it takes them: whatever is due and not
-- given up, soonest first, and first queued first among those due together.
create index email_queue_due on email_queue (due_at, queued) where given_up_at is null;

-- The requests already carried out, so that one sent twice happens once.
--
-- A request sent twice carries the same id both times, and the key on that id
-- is what decides which of them goes on: the insert is the claim. It is
-- written in the transaction of the request that made it, so an id is
-- remembered if and only if the work it names was kept. Moments are timestamps
-- in UTC.
--
-- The id is whatever whoever asked gave, and is nobody's secret: it says only
-- that a request by that name was carried out.
create table handled_requests (
    request_id  text        primary key,
    handled_at  timestamptz not null
);

-- What the forgetting asks: which claims have gone stale. Claiming takes them
-- out as it goes, so this is read as often as claims are made.
create index handled_requests_by_age on handled_requests (handled_at);

-- What has been written to whoever, kept after the email itself has been sent
-- and dropped from the queue, because the limit registering keeps is on what
-- was sent rather than on what is still waiting. It holds no address as it
-- was given: whom is an account by its id ("account:" and the id), and an
-- address with no account by the same keyed hash the accounts read model
-- finds an address by, which is no use to anyone without the key. A reader who
-- has forgotten their password gives an address, and an address with no
-- account is sent a link to register instead; that email fills an inbox
-- exactly as the others do, and the limit that keeps an inbox from being
-- buried has to count it. Moments are timestamps in UTC.
create table emails_written (
    id          bigserial   primary key,
    written_to  text        not null,
    kind        text        not null,
    written_at  timestamptz not null
);

-- What the limit asks: how much has been written to one whoever lately.
create index emails_written_by_whoever on emails_written (written_to, written_at);

-- A reader stays signed in by a cookie holding an id that means nothing by
-- itself. What is kept here is a hash of that id, never the id, so that
-- whoever takes this table takes nothing a browser could send back.
--
-- The account is kept beside it, so that every session an account has can be
-- ended at once: setting a new password does that, and so does forgetting the
-- account. Moments are timestamps in UTC, as everywhere else.
create table sessions (
    id_hash       text        primary key,
    account_id    text        not null,
    started_at    timestamptz not null,
    last_used_at  timestamptz not null
);

-- What ending every session an account has asks for.
create index sessions_by_account on sessions (account_id);

-- Every signing in that failed, so that the sign in page cannot be used to
-- guess passwords: an email address that has failed often enough is held for
-- an hour, and so is an IP address that has failed often enough whichever
-- address it gave.
--
-- It holds the address as it is found — trimmed and in lower case — rather than
-- as it was typed, so that writing it another way does not count afresh. A row
-- is written only when a signing in fails, so nothing here says which
-- addresses have accounts: an address nobody registered is counted exactly as
-- one that is.
create table failed_sign_ins (
    id            bigserial   primary key,
    email_address text        not null,
    ip_address    text        not null,
    failed_at     timestamptz not null
);

-- What each limit asks: how often one address, or one IP address, has failed
-- lately.
create index failed_sign_ins_by_email_address on failed_sign_ins (email_address, failed_at);
create index failed_sign_ins_by_ip_address on failed_sign_ins (ip_address, failed_at);

-- Every time somebody asked for a way back in, by the address they asked from,
-- so that the forgot password page cannot be used to try address after
-- address. It holds no email address: how often an address is written to is
-- counted where every email is counted (emails_written), and this is only the
-- asking.
create table password_reset_askings (
    id          bigserial   primary key,
    ip_address  text        not null,
    asked_at    timestamptz not null
);

-- What the limit asks: how often one IP address has asked lately.
create index password_reset_askings_by_ip_address on password_reset_askings (ip_address, asked_at);

-- Accounts by a keyed hash of the subject Google knows their Google account by,
-- never the subject itself, so that the table says nothing to anybody without
-- the key. A Google account is linked to one account and an account to one
-- Google account. A forgotten account's row is deleted, since nothing is ever
-- to find it by its Google account again, and that frees the Google account to
-- be linked to another.
create table accounts_by_google_account (
    account_id   text primary key,
    subject_hash text not null unique
);

-- Every address a tournament has ever been found at, and the tournament it
-- leads to. An address is kept after the tournament moves, since an old link
-- still leads to it, and so is never given to another tournament: the address
-- is the key, and a tournament can hold many.
create table tournaments_by_address (
    address       text primary key,
    tournament_id text not null
);

-- Each tournament held once, for every read model of tournaments, with what is
-- true of it whoever asks. The home page's list, the admin's and the search
-- join to it and keep beside it only what is theirs, so that a tournament
-- changed is one row changed, and making somebody a manager has nothing to copy
-- from another account's row. The website is kept as the tournament was
-- created, since a tournament keeps the one it was created on.
--
-- A world ranking officer's list is every tournament of the sports whose
-- players it looks after. Whether a tournament counts towards the world
-- rankings is not kept here, since each of its competitions says for itself.
create table tournaments (
    tournament_id text    primary key,
    website       text    not null,
    name          text    not null,
    starts        date    not null,
    finishes      date    not null,
    address       text    not null,
    country       text    not null,
    region        text,
    sport         text    not null,
    archived      boolean not null default false,
    national      boolean not null default false,
    international boolean not null default false
);

create index tournaments_by_website_and_start on tournaments (website, starts);

-- The tournament each competition is in, whether it is archived and whether it
-- counts towards the world rankings. A competition's own events do not say
-- which tournament it is in, and its tournament's do, so this is written from
-- the tournament's stream and a competition's games, kept by the home page, are
-- put together with it when asked.
create table competitions (
    competition_id text    primary key,
    tournament_id  text    not null,
    world_rankings boolean not null default false,
    archived       boolean not null default false
);

create index competitions_by_tournament on competitions (tournament_id);

-- Each account's part in a tournament: one row an account, since an account
-- that manages a tournament does not also score it.
create table tournaments_by_account (
    tournament_id text not null,
    account_id    text not null,
    part          text not null check (part in ('manager', 'scorer')),
    primary key (tournament_id, account_id)
);

create index tournaments_by_account_account on tournaments_by_account (account_id);

-- Each game by its competition, and when it was added, which is when the
-- event adding it happened and is not changed by correcting it or restoring
-- it.
create table tournaments_by_website_games (
    competition_id text not null,
    game_id        text not null,
    added_at       timestamptz not null,
    archived       boolean not null default false,
    primary key (competition_id, game_id)
);

-- What every page of a tournament says of the notes its managers wrote: each
-- note's title, when it was written and when it last changed, and which
-- tournament it is of. No description: a note's description may be 750,000
-- characters, and is read from the note's own stream, only when that note is
-- read. Two notes written at the same moment are told apart by their ids, the
-- greater first, since the order rows were made in is not the order they were
-- first made in once a rebuild takes the notes' streams in no order but each
-- stream's own.
--
-- Each note's slug, where it is found among its tournament's notes, and
-- whether it has been deleted. A deleted note keeps its row, marked, so that
-- its slug stays taken and a note added after it is never found where it was;
-- it is found nowhere else. No two notes of a tournament have the same slug.
create table manager_notes_by_tournament (
    note_id       text    primary key,
    tournament_id text    not null,
    title         text    not null,
    written_at    timestamptz not null,
    changed_at    timestamptz not null,
    slug          text    not null,
    deleted       boolean not null default false
);

create index manager_notes_by_tournament_tournament
    on manager_notes_by_tournament (tournament_id);

create unique index manager_notes_by_tournament_slug
    on manager_notes_by_tournament (tournament_id, slug);

-- A tournament's commentaries, as every page of the tournament lists them and
-- finds them: its tournament, its title, its slug, its writer, when it was
-- started and when it last changed. It holds no comment.
--
-- No two commentaries on a tournament have the same slug, or the same title
-- however it is capitalised, which the keys hold to should two be started at
-- once.
create table commentaries_by_tournament (
    commentary_id text primary key,
    tournament_id text not null,
    title         text not null,
    slug          text not null,
    writer_id     text not null,
    started_at    timestamptz not null,
    changed_at    timestamptz not null
);

create unique index commentaries_by_tournament_slug
    on commentaries_by_tournament (tournament_id, slug);

create unique index commentaries_by_tournament_title
    on commentaries_by_tournament (tournament_id, lower(title));

-- The accounts forgotten, heard of from their own streams, whose commentaries
-- are not found, since a forgotten account is not one a reader is shown
-- anything of. Kept apart from the commentaries, so that a forgetting heard of
-- before the commentary's start still counts once the start is.
create table commentaries_by_tournament_forgotten (
    account_id text primary key
);

-- The accounts holding each role, for an administrator to list them. Nothing
-- can replay every account's events to find out, so this keeps the answer as
-- roles are given and taken. It keeps no name: a name is personal, kept
-- sealed in the account's own events, and read from there.
create table accounts_by_role (
    account_id text not null,
    role       text not null,
    primary key (role, account_id)
);

-- The players the world rankings know, by their full names, imported from the
-- rankings' own lists and replaced whole each time. A table for each sport,
-- since the two lists are not the same players. Not projected: nothing on the
-- site records them as events, since they are the rankings' and not the
-- site's.
create table ac_world_ranking_players (
    name text primary key
);

create table gc_world_ranking_players (
    name text primary key
);

-- The documents the import from the old sites refused, with why. Made with the
-- site's own tables rather than by the import, so that the administrator's
-- page for them finds the table on a site the import has never run on, and
-- answers none. Not projected: nothing on the site records them as events.
--
-- A document can be refused more than once, so nothing here is unique; the
-- number is what keeps the messages in the order they were kept.
--
-- The tournament each error is of, where the import knew it: its address and
-- its name as the site has them, and the name of the competition the document
-- was, where it was one, so that the administrator's page for a document can
-- link to the tournament on the site and on the old site, and say what it
-- was. Empty where the import refused the document before it knew of any
-- tournament, as for a tournament refused itself.
--
-- Where the document is: its path on the site, and on the old site it came
-- from, without a leading slash. A competition's own page where the document
-- was a competition the site has, and its tournament's page otherwise. Kept
-- rather than worked out from the tournament's address, since a competition's
-- slug on the site is made from its name and need not be the slug the old
-- site gave it. Empty where the import knew no tournament.
--
-- What went wrong, said for a person rather than for whoever reads the code:
-- "Game Tim 26 beat Trev 0 in Spring Open - Knockout because they are not
-- drawn to play each other.", for the administrator's pages to show above the
-- message the code wrote. In English, as the rest of what the import says is.
-- Empty where the import has no such saying for what it refused.
create table import_errors (
    kept              bigint generated always as identity primary key,
    document_id       text   not null,
    error_message     text   not null,
    tournament_address text,
    tournament_name    text,
    competition_name   text,
    new_site_path      text,
    old_site_path      text,
    summary            text
);

create index import_errors_by_document_id on import_errors (document_id);

-- What the website's search looks in: the names of its tournaments, of their
-- competitions and of their players, each kept beside the same name folded as
-- a search folds what is typed (accents off, lower case, one space between
-- words), so that finding one is a comparison and not a transformation of
-- every name there is. The tournament itself is held once, for every read model
-- of tournaments, and only its folded name is the search's to keep.
create table search_by_website_tournament_names (
    tournament_id text primary key,
    folded_name   text not null
);

-- A competition is told apart in the search by its name and its slug. Which
-- tournament it is in, and whether it is archived, are the competition's, held
-- once. A test is not searched for, so it has no row here.
create table search_by_website_competitions (
    competition_id text primary key,
    name           text not null,
    folded_name    text not null,
    slug           text not null
);

-- Every player of every tournament, a team's included, by the world ranking
-- name they are known by. `person` is the slug of that name, which is what
-- makes two players one person and is where the person's page is found, so
-- it is the access path of both the page and the search's grouping. `slug` is
-- the slug the tournament gave the player, which is where their own page in it
-- is. The players of a team that is archived are not found, and a team's
-- events say it of the team and not of its players, so each player is kept
-- with the team they are in, where they are in one.
--
-- `representing` is what each player represents, so that the player dialog can
-- offer what players have been added representing
-- (RepresentingMatching.feature). `kept` orders the players by when they were
-- first kept, which is how a club written two ways that differ only in
-- capitals is offered as it was first written. Identity rather than a clock,
-- since two players kept in one transaction share a moment and a rebuild keeps
-- them in the order it reads.
create table search_by_website_players (
    player_id          text primary key,
    tournament_id      text not null,
    name               text not null,
    world_ranking_name text not null,
    folded_name        text not null,
    person             text not null,
    archived           boolean not null default false,
    team_id            text,
    slug               text not null,
    representing       text,
    kept               bigint generated always as identity
);

create index search_by_website_players_tournament
    on search_by_website_players (tournament_id);

create index search_by_website_players_person
    on search_by_website_players (person);

create table search_by_website_teams (
    team_id  text primary key,
    archived boolean not null default false
);

-- A second copy of the lines the server writes to its log, for an
-- administrator to read at /admin/administrator/logs without being on the
-- machine (PostgresServerLog.feature). The log file is still the log; this is
-- kept for seven days and then removed.
--
-- `severity` is the number the log writes the level in, 10 for Trace to 60 for
-- Fatal, so that "this severity and more severe" is a comparison. `details` is
-- the whole line, since which fields a line carries is the log's to decide and
-- not this table's, and a reference from an error page is found in it.
create table server_log (
    kept       bigint generated always as identity primary key,
    written_at timestamptz not null,
    severity   smallint    not null,
    message    text        not null,
    details    jsonb       not null
);

-- What the newest-first reading and the removal of the old both go by.
create index server_log_by_written_at on server_log (written_at, kept);

-- The help, made searchable (PostgresHelpSearchIndex.feature). It is built into
-- files by "npm run build:help" and read from them; this is a copy of the words
-- of those files in the form Postgres searches, made again whenever the build
-- changes, so nothing here is the only place anything is kept and the table can
-- be emptied without losing a word of the help.

create table help_search_pages (
    language_tag text     not null,
    name         text     not null,
    title        text     not null,
    headings     text     not null,
    body         text     not null,
    -- The rules of the page's language that its words were cut and stemmed by,
    -- kept with the page so that what is searched for is cut by the same ones.
    rules        regconfig not null,
    -- Weighed so that a word in a title counts for more than the same word in a
    -- heading, and in a heading for more than in a paragraph. Generated, so
    -- that it can never disagree with the words it is made from.
    document     tsvector generated always as (
        setweight(to_tsvector(rules, title), 'A') ||
        setweight(to_tsvector(rules, headings), 'B') ||
        setweight(to_tsvector(rules, body), 'C')
    ) stored,
    primary key (language_tag, name)
);

create index help_search_pages_document on help_search_pages using gin (document);

-- What the pages here were made from, so that making them again from the same
-- help can be seen to be needless. One row, kept by its key.
--
-- `page_count` is how many pages the fingerprint was made for, so that an index
-- that has lost some of them is seen to have, and is made again, instead of
-- being taken for the help it was made from because the fingerprint still
-- matches.
create table help_search_state (
    only_row    boolean primary key default true check (only_row),
    fingerprint text    not null,
    page_count  integer not null default 0
);
