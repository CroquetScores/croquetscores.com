-- A number the database gives each event as it is kept, which only goes up. A
-- stream and its version say which event it is; this says where, among every
-- event there is, it was kept, so that somebody who has read as far as a
-- number can ask for what came after it without comparing every stream.
--
-- Given by default and not always, so that a copy of the events kept
-- somewhere else can keep the number it was given here: the copy is then asked
-- how far it has got by its highest number.
--
-- What is there is numbered as the table is rewritten, in the order the
-- database finds it. Which of two events a number puts first is only meant of
-- events kept after this.
alter table events add column id bigint generated by default as identity;

create unique index events_by_id on events (id);
