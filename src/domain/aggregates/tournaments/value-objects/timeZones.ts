/**
 * The time zone, by its name in the zone database, of a tournament played in
 * the country coded `country` and, where it has one, the region coded
 * `region`. A country not listed is on Greenwich's time, which is how a game
 * is kept, so that a gap in the table shows as a day that is nobody's wrong
 * by more than a few hours rather than as a failure.
 */
export const timeZoneOf = (
  country: string,
  region: string | undefined,
): string =>
  (region === undefined ? undefined : regionZones[country]?.[region]) ??
  countryZones[country] ??
  "UTC";

/**
 * The day, as "2026-10-03", that the moment `at` falls on in the time zone
 * `timeZone`.
 */
export const dayInTimeZone = (at: Date, timeZone: string): string =>
  // Sweden writes a date as year, month and day joined by hyphens, which is
  // the form wanted, so the parts need not be put together by hand.
  new Intl.DateTimeFormat("sv-SE", {
    timeZone,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(at);
